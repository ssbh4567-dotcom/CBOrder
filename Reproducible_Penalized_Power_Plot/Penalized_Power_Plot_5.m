%% Local Function Definition
function plot_power(c, power_CBLRT, power_CBMax, power_CBMaxMin, power_CBMin, CBMinMax, title_str, show_legend)
    % Increased LineWidth to 2 and MarkerSize to 8
    h1 = plot(c, power_CBLRT, '-', 'Color', [0.5 0.5 0.5], 'LineWidth', 2, ...
        'Marker', 's', 'MarkerFaceColor', [0.5 0.5 0.5], 'MarkerSize', 6.5);
    hold on; 
    h2 = plot(c, power_CBMax, '--', 'Color', [0 0.8 0], 'LineWidth', 2, ... % slightly darkened green for better contrast
        'Marker', '^', 'MarkerFaceColor', [0 0.8 0], 'MarkerSize', 6.5);
    h3 = plot(c, power_CBMaxMin, '-.', 'Color', [1 0 0], 'LineWidth', 2, ...
        'Marker', 'p', 'MarkerFaceColor', [1 0 0], 'MarkerSize', 9); % pentagram needs slightly larger size to match visually
    h4 = plot(c, power_CBMin, ':', 'Color', [0 0 1], 'LineWidth', 2.5, ... % dotted lines need slightly more width to show clearly
        'Marker', 'd', 'MarkerFaceColor', [0 0 1], 'MarkerSize', 6.5);
    h5 = plot(c, CBMinMax, '-', 'Color', [0.2 0.6 1], 'LineWidth', 2, ... % darkened light blue for better visibility
        'Marker', 'o', 'MarkerFaceColor', [0.2 0.6 1], 'MarkerSize', 6.5);
        
    % Configure plot appearance
    set(gca, 'FontSize', 14, 'FontWeight', 'bold', 'LineWidth', 1.2); % Thicker axes lines
    xlim([0 5.1]);
    ylim([0 1.05]);
    
    % Enlarged Title and Labels
    title(title_str, 'FontWeight', 'bold', 'FontSize', 18);
    xlabel('c', 'FontSize', 16, 'FontAngle', 'italic', 'FontWeight', 'bold');
    ylabel('Power', 'FontSize', 16, 'FontWeight', 'bold');
  
    if show_legend
        % Enlarged Legend
        legend([h1, h2, h3, h4, h5], {'CBLRT', 'CBMax', 'CBMaxMin', 'CBMin', 'CBMinMax'}, ...
            'Location', 'southeast', 'Box', 'off', 'FontSize', 13, 'FontWeight', 'bold');
    end
    hold off; % Release the hold
end

